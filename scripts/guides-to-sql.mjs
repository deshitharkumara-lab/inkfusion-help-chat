// Builds a one-time SQL seed from guides/**/*.yaml.
// Usage: node scripts/guides-to-sql.mjs > migrations/0002_seed_guides.sql
// After the first deploy, guides are managed in the admin page (the database
// is the source of truth). INSERT OR IGNORE never overwrites admin edits.
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import YAML from "yaml";

const root = new URL("../guides/", import.meta.url).pathname;
const files = [];
for (const dir of readdirSync(root)) {
  const p = join(root, dir);
  if (!statSync(p).isDirectory()) continue;
  for (const f of readdirSync(p)) if (f.endsWith(".yaml")) files.push(join(p, f));
}
const q = (s) => "'" + String(s).replaceAll("'", "''") + "'";
let out = "-- Generated by scripts/guides-to-sql.mjs. Seeds the starter fix-guide library.\n";
for (const f of files.sort()) {
  const src = readFileSync(f, "utf8");
  const g = YAML.parse(src);
  const machine = Array.isArray(g.machine) ? g.machine : [g.machine];
  out += `INSERT OR IGNORE INTO guides (id, machine, problem, yaml, status) VALUES (${q(g.id)}, ${q(JSON.stringify(machine))}, ${q(g.problem)}, ${q(src)}, ${q(g.status)});\n`;
}
process.stdout.write(out);
